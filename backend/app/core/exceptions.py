async def app_exception_handler(request: Request, exc: AppException) -> JSONResponse:
    """Exception handler for custom domain AppException instances."""
    cid = getattr(request.state, "correlation_id", get_correlation_id() or "")
    problem = ProblemDetail(
        type=exc.error_type,
        title=exc.title,
        status=exc.status_code,
        detail=exc.detail,
        instance=request.url.path,
        correlation_id=cid,
        invalid_params=exc.invalid_params,
    )
    headers = {"X-Correlation-ID": cid, "X-Request-ID": cid}
    if isinstance(exc, RateLimitExceededError):
        headers["Retry-After"] = str(exc.retry_after_seconds)

    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        media_type="application/problem+json",
        headers=headers,
    )


async def validation_exception_handler(
    request: Request, exc: RequestValidationError
) -> JSONResponse:
    """Exception handler translating FastAPI RequestValidationError into RFC 7807 Problem Details."""
    cid = getattr(request.state, "correlation_id", get_correlation_id() or "")
    invalid_params: list[InvalidParam] = []

    for err in exc.errors():
        loc = " -> ".join(str(item) for item in err.get("loc", []))
        msg = err.get("msg", "Validation failed")
        err_type = err.get("type")
        input_val = err.get("input")
        # Ensure input_val is serializable
        if not isinstance(input_val, (str, int, float, bool, list, dict, type(None))):
            input_val = str(input_val)

        invalid_params.append(
            InvalidParam(
                field=loc,
                message=msg,
                error_type=err_type,
                input_value=input_val,
            )
        )

    problem = ProblemDetail(
        type="https://travelops.ai/errors/validation-error",
        title="Unprocessable Entity",
        status=status.HTTP_422_UNPROCESSABLE_ENTITY,
        detail="One or more request parameters failed validation.",
        instance=request.url.path,
        correlation_id=cid,
        invalid_params=invalid_params,
    )

    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content=problem.model_dump(exclude_none=True),
        media_type="application/problem+json",
        headers={"X-Correlation-ID": cid, "X-Request-ID": cid},
    )


async def http_exception_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
    """Exception handler translating Starlette/FastAPI HTTPExceptions into RFC 7807 Problem Details."""
    cid = getattr(request.state, "correlation_id", get_correlation_id() or "")
    titles = {
        400: "Bad Request",
        401: "Unauthorized",
        403: "Forbidden",
        404: "Resource Not Found",
        405: "Method Not Allowed",
        408: "Request Timeout",
        409: "Conflict",
        422: "Unprocessable Entity",
        429: "Too Many Requests",
        500: "Internal Server Error",
        502: "Bad Gateway",
        503: "Service Unavailable",
    }
    title = titles.get(exc.status_code, "HTTP Error")
    detail = str(exc.detail) if exc.detail else title

    problem = ProblemDetail(
        type=f"https://travelops.ai/errors/http-{exc.status_code}",
        title=title,
        status=exc.status_code,
        detail=detail,
        instance=request.url.path,
        correlation_id=cid,
    )

    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        media_type="application/problem+json",
        headers={"X-Correlation-ID": cid, "X-Request-ID": cid},
    )


async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Global catch-all exception handler protecting against stack trace leaks."""
    cid = getattr(request.state, "correlation_id", get_correlation_id() or "")
    logger.error(
        f"Unhandled application exception on {request.method} {request.url.path} (cid={cid}): {exc}",
        exc_info=True,
    )

    problem = ProblemDetail(
        type="https://travelops.ai/errors/internal-server-error",
        title="Internal Server Error",
        status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        detail="An internal server error occurred. Please contact system administrator with the correlation ID.",
        instance=request.url.path,
        correlation_id=cid,
    )

    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=problem.model_dump(exclude_none=True),
        media_type="application/problem+json",
        headers={"X-Correlation-ID": cid, "X-Request-ID": cid},
    )
