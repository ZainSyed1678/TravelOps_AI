"""RFC 7807 Problem Details and normalized domain exceptions for TravelOps AI."""

from datetime import UTC, datetime
from typing import Any

from fastapi import Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from starlette.exceptions import HTTPException as StarletteHTTPException

from app.core.context import get_correlation_id
from app.core.logging import logger


class InvalidParam(BaseModel):
    """Parameter-level error detail for validation failures."""

    field: str
    message: str
    error_type: str | None = None
    input_value: Any | None = None


class ProblemDetail(BaseModel):
    """RFC 7807 compliant problem details schema."""

    type: str = Field(
        default="https://travelops.ai/errors/general-error",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        default="An error occurred",
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        default=400,
        description="The HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        default="",
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str = Field(
        default="",
        description="A URI reference that identifies the specific occurrence of the problem.",
    )
    correlation_id: str = Field(
        default="",
        description="Distributed request tracing correlation ID.",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat(),
        description="UTC timestamp when the error occurred.",
    )
    invalid_params: list[InvalidParam] | None = Field(
        default=None,
        description="List of invalid fields when status is 422.",
    )


class AppException(Exception):
    """Base application exception for standardized error reporting."""

    def __init__(
        self,
        detail: str,
        status_code: int = status.HTTP_400_BAD_REQUEST,
        title: str = "Bad Request",
        error_type: str = "https://travelops.ai/errors/bad-request",
        invalid_params: list[InvalidParam] | None = None,
    ) -> None:
        super().__init__(detail)
        self.detail = detail
        self.status_code = status_code
        self.title = title
        self.error_type = error_type
        self.invalid_params = invalid_params


class NotFoundError(AppException):
    """Entity or resource not found error (HTTP 404)."""

    def __init__(self, detail: str = "Requested resource was not found") -> None:
        super().__init__(
            detail=detail,
            status_code=status.HTTP_404_NOT_FOUND,
            title="Resource Not Found",
            error_type="https://travelops.ai/errors/not-found",
        )


